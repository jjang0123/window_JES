# 입력 방법2: input() 2번 사용
num1 = int(input("첫 번째 정수를 입력하세요: "))
num2 = int(input("두 번째 정수를 입력하세요: "))

# 출력 방법2: format() 메소드 방식
print("{}  +  {} = {}".format(num1, num2, num1 + num2))
print("{}  -  {} = {}".format(num1, num2, num1 - num2))
print("{}  x  {} = {}".format(num1, num2, num1 * num2))
print("{}  /  {} = {}".format(num1, num2, num1 / num2))