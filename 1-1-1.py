# 입력 방법1: input() 1번 사용
num1 = int(input("첫 번째 정수를 입력하세요: "))
num2 = int(input("두 번째 정수를 입력하세요: "))

# 출력 방법1: f-스트링 방식으로 출력
print(f"{num1}  +  {num2} = {num1 + num2}")
print(f"{num1}  -  {num2} = {num1 - num2}")
print(f"{num1}  x  {num2} = {num1 * num2}")
print(f"{num1}  /  {num2} = {num1 / num2}")